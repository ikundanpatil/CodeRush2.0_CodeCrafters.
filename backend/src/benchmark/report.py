"""Phase 9 improvement report: a plain, deterministic serialization of a
StrategyComparisonResult. Every sentence here is generated by string
formatting over already-computed numbers -- never by asking an LLM to
summarize or judge the comparison, so a claim like "improved by 8.8%" can
always be traced back to StrategyComparator's arithmetic.
"""

from typing import Any, Dict

from src.benchmark.models import ComparisonStatus, StrategyComparisonResult

_STATUS_SUMMARY = {
    ComparisonStatus.IMPROVED: "The candidate strategy improved over the baseline.",
    ComparisonStatus.REGRESSED: "The candidate strategy performed worse than the baseline.",
    ComparisonStatus.UNCHANGED: "The candidate strategy showed no meaningful difference from the baseline.",
    ComparisonStatus.MIXED: "The candidate strategy improved on some benchmarks and regressed on others.",
}


def generate_improvement_report(comparison: StrategyComparisonResult) -> Dict[str, Any]:
    pct = comparison.improvement_percentage
    pct_text = "n/a (baseline score was zero)" if pct is None else f"{pct:+.2f}%"

    summary = (
        f"{_STATUS_SUMMARY[comparison.status]} "
        f"Baseline score {comparison.baseline_score:.3f} -> candidate score {comparison.candidate_score:.3f} "
        f"(absolute change {comparison.absolute_improvement:+.3f}, {pct_text}). "
        f"{len(comparison.improvements)} benchmark(s) improved, {len(comparison.regressions)} regressed."
    )

    return {
        "status": comparison.status.value,
        "summary": summary,
        "baseline_strategy_id": comparison.baseline_strategy_id,
        "candidate_strategy_id": comparison.candidate_strategy_id,
        "baseline_score": comparison.baseline_score,
        "candidate_score": comparison.candidate_score,
        "absolute_improvement": comparison.absolute_improvement,
        "improvement_percentage": comparison.improvement_percentage,
        "improvements": comparison.improvements,
        "regressions": comparison.regressions,
    }
